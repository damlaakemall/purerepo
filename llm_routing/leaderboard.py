"""Collect every runs/**/metrics.json into one comparison table (markdown).

Runs are grouped by benchmark *fingerprint*: numbers are only put side by side when
they were computed on byte-identical data. Seeds are aggregated as mean ± std.
"""

from __future__ import annotations

import glob
import json
import os
from collections import defaultdict

import numpy as np

COLUMNS = [("aiq", "AIQ ↑"), ("cost_to_match_reference", "cost to match best ↓"),
           ("cost_advantage@drop<=1%", "small-model share @≤1% drop ↑"), ("quality_drop_pct@40%", "drop % @40% ↓")]


def collect(runs_dir: str = "runs") -> list[dict]:
    out = []
    for p in glob.glob(os.path.join(runs_dir, "**", "metrics.json"), recursive=True):
        with open(p) as f:
            out.append(json.load(f))
    return out


def build_table(records: list[dict]) -> str:
    groups = defaultdict(lambda: defaultdict(list))  # (bench, fp, models) -> (router label) -> [result]
    for rec in records:
        key = (rec["benchmark"], rec["fingerprint"], " vs ".join(rec["models"]))
        for r in rec["results"]:
            label = r["router"] + (" (baseline)" if r.get("is_baseline") else "")
            # the same baseline is evaluated by every experiment on this data: count each seed once
            if r.get("is_baseline") and any(x["_seed"] == rec["seed"] for x in groups[key][label]):
                continue
            groups[key][label].append({**r, "_seed": rec["seed"]})
    lines = []
    for (bench, fp, models), routers in sorted(groups.items()):
        lines += [f"### {bench} — models: {models}", f"data fingerprint `{fp}`", "",
                  "| router | seeds | " + " | ".join(h for _, h in COLUMNS) + " |",
                  "|---|---|" + "---|" * len(COLUMNS)]
        for label, rs in sorted(routers.items(), key=lambda kv: (kv[0].endswith("(baseline)"), kv[0])):
            cells = []
            for k, _ in COLUMNS:
                vals = [r[k] for r in rs if isinstance(r.get(k), (int, float))]
                if not vals:
                    cells.append("–")
                elif not np.all(np.isfinite(vals)):
                    cells.append("∞ (never)")
                elif len(vals) == 1:
                    cells.append(f"{vals[0]:.4g}")
                else:
                    cells.append(f"{np.mean(vals):.4g} ± {np.std(vals):.2g}")
            lines.append(f"| {label} | {len(rs)} | " + " | ".join(cells) + " |")
        lines.append("")
    return "\n".join(lines)


def write_leaderboard(runs_dir: str = "runs", out: str = "results/leaderboard.md") -> str:
    table = build_table(collect(runs_dir))
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write("# Leaderboard\n\nGenerated by `llmr leaderboard` from `runs/**/metrics.json`. "
                "Metric definitions: [docs/evaluation.md](../docs/evaluation.md).\n\n" + table)
    return table
